// query builds a DNS query for an A record of name with the given ID.
func query(id uint16, name string) []byte {
	q := make([]byte, 12)
	binary.BigEndian.PutUint16(q, id)
	q[2] = 0x01 // RD
	binary.BigEndian.PutUint16(q[4:], 1)
	for _, label := range strings.Split(name, ".") {
		q = append(q, byte(len(label)))
		q = append(q, label...)
	}
	return append(q, 0, 0, 1, 0, 1)
}

// fakeNS is a nameserver on loopback that answers every query with a
// canned A record and records the transports it was asked over.
type fakeNS struct {
	addr string
	seen chan string
	pc   net.PacketConn
	ln   net.Listener
}

func startFakeNS(t *testing.T) *fakeNS {
	t.Helper()
	pc, err := net.ListenPacket("udp4", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	ln, err := net.Listen("tcp4", pc.LocalAddr().String())
	if err != nil {
		_ = pc.Close()
		t.Skipf("cannot listen on %s over TCP: %v", pc.LocalAddr(), err)
	}
	ns := &fakeNS{addr: pc.LocalAddr().String(), seen: make(chan string, 16), pc: pc, ln: ln}
	t.Cleanup(func() { _ = pc.Close(); _ = ln.Close() })
	go func() {
		buf := make([]byte, DNSMaxMessage)
		for {
			n, addr, err := pc.ReadFrom(buf)
			if err != nil {
				return
			}
			ns.seen <- "udp"
			_, _ = pc.WriteTo(answer(buf[:n]), addr)
		}
	}()
	go func() {
		for {
			c, err := ln.Accept()
			if err != nil {
				return
			}
			go func() {
				defer func() { _ = c.Close() }()
				for {
					q, err := readFramed(c)
					if err != nil {
						return
					}
					ns.seen <- "tcp"
					if err := writeFramed(c, answer(q)); err != nil {
						return
					}
				}
			}()
		}
	}()
	return ns
}

// answer returns q as a response carrying one A record, 192.0.2.1.
func answer(q []byte) []byte {
	i := 12
	for i < len(q) && q[i] != 0 {
		i += int(q[i]) + 1
	}
	r := append([]byte(nil), q[:i+5]...)
	r[2], r[3] = 0x81, 0x80
	binary.BigEndian.PutUint16(r[6:], 1)
	return append(r, 0xc0, 0x0c, 0, 1, 0, 1, 0, 0, 0, 60, 0, 4, 192, 0, 2, 1)
}

func resolvConfWith(t *testing.T, lines ...string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "resolv.conf")
	if err := os.WriteFile(path, []byte(strings.Join(lines, "\n")+"\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

func TestParseResolvConf(t *testing.T) {
	ns, rest := ParseResolvConf([]byte(`# Generated by NetworkManager
search home example.test ; trailing
nameserver 1.1.1.1
nameserver 2a00:11b4:4110::a
nameserver 127.0.0.1:5353
nameserver [::1]:5353
nameserver not-an-address
nameserver
options edns0 trust-ad
`))
	if want := []string{"1.1.1.1:53", "[2a00:11b4:4110::a]:53", "127.0.0.1:5353", "[::1]:5353"}; strings.Join(ns, " ") != strings.Join(want, " ") {
		t.Errorf("nameservers = %v, want %v", ns, want)
	}
	if want := []string{"search home example.test", "options edns0 trust-ad"}; strings.Join(rest, "|") != strings.Join(want, "|") {
		t.Errorf("rest = %v, want %v", rest, want)
	}
	r := &Resolver{ResolvConf: filepath.Join(t.TempDir(), "missing")}
	if got := r.Nameservers(); len(got) != 1 || got[0] != "127.0.0.1:53" {
		t.Errorf("Nameservers() without a file = %v, want the libc default", got)
	}
}

func TestResolverExchange(t *testing.T) {
	ns := startFakeNS(t)
	// The first nameserver is unreachable; the next one answers.
	r := &Resolver{ResolvConf: resolvConfWith(t, "nameserver 127.0.0.1:1", "nameserver "+ns.addr), Timeout: 500 * time.Millisecond}
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	for _, tcp := range []bool{false, true} {
		q := query(0x1234, "github.com")
		resp, err := r.Exchange(ctx, q, tcp)
		if err != nil {
			t.Fatalf("tcp=%v: %v", tcp, err)
		}
		if !bytes.Equal(resp[:2], q[:2]) || resp[2]&0x80 == 0 || !bytes.HasSuffix(resp, []byte{192, 0, 2, 1}) {
			t.Errorf("tcp=%v: response %x", tcp, resp)
		}
		want := "udp"
		if tcp {
			want = "tcp"
		}
		if got := <-ns.seen; got != want {
			t.Errorf("query went over %s, want %s", got, want)
		}
	}
	if _, err := r.Exchange(ctx, []byte("short"), false); err == nil {
		t.Error("a message shorter than a header must be refused")
	}
	r.ResolvConf = resolvConfWith(t, "nameserver 127.0.0.1:1")
	if _, err := r.Exchange(ctx, query(1, "x"), false); err == nil {
		t.Error("expected an error when no nameserver answers")
	}
}

func TestServFail(t *testing.T) {
	q := query(0xabcd, "example.org")
	r := ServFail(q)
	if r[0] != 0xab || r[1] != 0xcd || r[2] != 0x81 || r[3] != 0x82 ||
		binary.BigEndian.Uint16(r[4:]) != 1 || binary.BigEndian.Uint16(r[6:]) != 0 ||
		!bytes.Equal(r[12:], q[12:]) {
		t.Errorf("ServFail = %x", r)
	}
	if ServFail([]byte{1, 2, 3}) != nil {
		t.Error("a truncated query has no answer")
	}
}

// startDNS runs a proxy with the given resolver on a unix socket and a
// forwarder relaying to it from loopback listeners, returning the
// forwarder's UDP and TCP addresses and the proxy's log.
func startDNS(t *testing.T, r *Resolver) (udp, tcp string, logs *bytes.Buffer) {
	t.Helper()
	sock := filepath.Join(t.TempDir(), "p.sock")
	ln, err := net.Listen("unix", sock)
	if err != nil {
		t.Fatal(err)
	}
	logs = &bytes.Buffer{}
	srv := &Server{DNS: r, Log: log.New(logs, "", 0)}
	go func() { _ = srv.Serve(ln) }()
	t.Cleanup(func() { _ = ln.Close() })

	pc, err := net.ListenPacket("udp4", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	tl, err := net.Listen("tcp4", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	f := &DNSForwarder{Socket: sock, Timeout: 5 * time.Second}
	go func() { _ = f.ServeUDP(pc) }()
	go func() { _ = f.ServeTCP(tl) }()
	t.Cleanup(func() { _ = pc.Close(); _ = tl.Close() })
	return pc.LocalAddr().String(), tl.Addr().String(), logs
}

func TestDNSForwarder(t *testing.T) {
	ns := startFakeNS(t)
	udp, tcp, _ := startDNS(t, &Resolver{ResolvConf: resolvConfWith(t, "nameserver "+ns.addr)})

	// UDP: a datagram in, the upstream answer out.
	c, err := net.Dial("udp", udp)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = c.Close() }()
	_ = c.SetDeadline(time.Now().Add(5 * time.Second))
	q := query(7, "github.com")
	if _, err := c.Write(q); err != nil {
		t.Fatal(err)
	}
	buf := make([]byte, DNSMaxMessage)
	n, err := c.Read(buf)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(buf[:2], q[:2]) || !bytes.HasSuffix(buf[:n], []byte{192, 0, 2, 1}) {
		t.Errorf("udp response %x", buf[:n])
	}
	if got := <-ns.seen; got != "udp" {
		t.Errorf("udp query relayed over %s", got)
	}

	// TCP: two framed queries on one connection, answered over TCP upstream.
	tc, err := net.Dial("tcp", tcp)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = tc.Close() }()
	_ = tc.SetDeadline(time.Now().Add(5 * time.Second))
	for _, id := range []uint16{8, 9} {
		q := query(id, "example.org")
		if err := writeFramed(tc, q); err != nil {
			t.Fatal(err)
		}
		resp, err := readFramed(tc)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(resp[:2], q[:2]) || !bytes.HasSuffix(resp, []byte{192, 0, 2, 1}) {
			t.Errorf("tcp response %x", resp)
		}
		if got := <-ns.seen; got != "tcp" {
			t.Errorf("tcp query relayed over %s", got)
		}
	}
}

func TestDNSForwarderServFail(t *testing.T) {
	// No nameserver answers: the client gets SERVFAIL, and the proxy logs it.
	udp, _, logs := startDNS(t, &Resolver{ResolvConf: resolvConfWith(t, "nameserver 127.0.0.1:1"), Timeout: 200 * time.Millisecond})
	c, err := net.Dial("udp", udp)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = c.Close() }()
	_ = c.SetDeadline(time.Now().Add(5 * time.Second))
	q := query(3, "github.com")
	if _, err := c.Write(q); err != nil {
		t.Fatal(err)
	}
	buf := make([]byte, DNSMaxMessage)
	n, err := c.Read(buf)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(buf[:n], ServFail(q)) {
		t.Errorf("got %x, want SERVFAIL", buf[:n])
	}
	if !strings.Contains(logs.String(), "dns: 127.0.0.1:1") {
		t.Errorf("log = %q", logs.String())
	}
}

