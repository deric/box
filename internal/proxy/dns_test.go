func TestFramed(t *testing.T) {
	var b bytes.Buffer
	if err := writeFramed(&b, []byte("abc")); err != nil {
		t.Fatal(err)
	}
	if got := b.Bytes(); !bytes.Equal(got, []byte{0, 3, 'a', 'b', 'c'}) {
		t.Errorf("framed = %x", got)
	}
	msg, err := readFramed(&b)
	if err != nil || string(msg) != "abc" {
		t.Errorf("readFramed = %q, %v", msg, err)
	}
	if _, err := readFramed(&b); err != io.EOF {
		t.Errorf("readFramed on empty = %v, want EOF", err)
	}
	if err := writeFramed(&b, make([]byte, DNSMaxMessage+1)); err == nil {
		t.Error("an oversized message must be refused")
	}
}
